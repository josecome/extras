
# Loop through numbers from 0 up to, 
# but not including, 5
for i in range(5):
    print(i)  # Print the current number

# Loop through numbers from 2 up to, 
# but not including, 6
for i in range(2, 6):
    print(i)  # Print the current number

# Loop through numbers from 0 up to, but 
# not including, 10, counting by 2
for i in range(0, 10, 2):
    print(i)  # Print the current number